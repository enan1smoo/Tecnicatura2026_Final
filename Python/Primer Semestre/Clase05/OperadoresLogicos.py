# Operadores Logicos

# Operador AND
# Este operador tiene que tener ambos valores en Verdadero para devolver True en consola
#de lo contrario si un valor es Falso, devolvera False
a = True
b = True
resultado = a and b
print(resultado)

# Operador OR
# Este operador nos devolvera un True si UNO de los valores es Verdadero
# Solo devolvera False, si ambos valores son falsos
resultado = a or b
print(resultado)

# Operador NOT
# Este operador invierte el resultado de nuestra variable
c = True
d = False
resultado = not c
print(resultado)
resultado = not d
print(resultado)