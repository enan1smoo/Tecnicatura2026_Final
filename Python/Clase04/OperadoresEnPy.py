# Operando de suma
operandoA = 6
operandoB = 2
suma = operandoA + operandoB
print("Resultado de la suma: ", suma)
print(f"El resultado de la suma es: {suma}")

# Operando de resta
resta = operandoA - operandoB
print(f"El resultado de la resta es: {resta}")

# Operando de multiplicacion
multiplicacion = operandoA * operandoB
print(f"El resultado de la multiplicacion es: {multiplicacion}")

# Operando de division
division = operandoA / operandoB
print(f"El resultado de la division es: {division}")
# Operando de division, con muestra de resultado de tipo entero (int)
division = operandoA // operandoB
print(f"El resultado de la division (int) es: {division}")

# Operando de modulo o residuo
modulo = operandoA % operandoB
print(f"El resultado de la division o residuo (modulo) es: {modulo}")

# Operador de exponente
exponente = operandoA ** operandoB
print(f"El resultado de la exponente es: {exponente}")
