miVariable = 3
print(miVariable)

# Operadores de reasignación (incremento con reasignacion)
miVariable = miVariable + 1
print(miVariable)

# Otra manera de hacerlo
miVariable += 1
print(miVariable)

# Esto se puede hacer con los demas operadores aritmeticos
# miVariable = miVariable - 2
miVariable -= 2
print(miVariable)

# miVariable = miVariable * 3
miVariable *= 3
print(miVariable)

# miVariable = miVariable / 2
miVariable /= 2     #miVariable //= 2   Haciendolo de esta manera
print(miVariable)   #print(miVariable)  veremos un resultado de tipo int

# Operadores de Comparación

d = 4
b = 2
resultado = d == b # Comprobamos si son iguales
print(resultado)

# Operador diferente
resultado = d != b
print(resultado)

# Operador Mayor que
resultado = d > b
print(resultado)

# Operador Menor que
resultado = d < b
print(resultado)

# Operador Menor o Igual que
resultado = d <= b
print(resultado)

# Operador Mayor o Igual que
resultado = d >= b
print(resultado)
